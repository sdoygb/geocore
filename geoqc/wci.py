# Block (geometric) normal-Hessian correction — article 10.91 §6 eq (6.3)
# ---------------------------------------------------------------------------

def _gather_residual(local_idx, r_out_idx, r_out_vals):
    """Residual values on local_idx via sorted searchsorted; 0 where absent."""
    r_block = np.zeros(len(local_idx), dtype=float)
    if len(r_out_idx) == 0:
        return r_block
    pos = np.searchsorted(r_out_idx, local_idx)
    pc = np.clip(pos, 0, len(r_out_idx) - 1)
    match = r_out_idx[pc] == local_idx
    r_block[match] = r_out_vals[pc[match]]
    return r_block


def compute_block_pt2_correction(r_out_idx, r_out_vals, E0, apply_fn, hd_fn,
                                 db, az_of, bz_of, rt_a, rt_b,
                                 in_space_idx=None, n_centers=20,
                                 h_build_chunk=200, verbose=False):
    """Geometric block-Newton normal-Hessian correction (10.91 Lemma D, eq 6.3).

    The diagonal PT2 (compute_pt2_correction) treats every out-of-space
    determinant as independent:  H_N = Q(H-E0)Q is replaced by its diagonal.
    Here we use the Bruhat locality of H (10.88 Prop 2.03: a non-zero entry
    needs Bruhat distance <=2): the normal space is partitioned into disjoint
    Bruhat 2-balls centred on the largest-residual determinants, and within
    each ball the FULL dense normal-Hessian block is inverted, capturing all
    intra-ball single/double-excitation couplings:

        E_corr = -sum_k r_k^T (H_block_k - E0 I)^{-1} r_k.

    Balls are made disjoint by greedy first-come assignment; determinants
    already in the variational space V are excluded (normal space = V perp).
    Inter-ball coupling exists only between balls whose centres are at
    Bruhat distance 3-4 (zero when >4); it is left for block-Jacobi sweeps
    (10.91 §9.1, convergence iff rho(D^-1 O)<1).  One call = one block-diagonal
    sweep (the dominant term); jacobi iteration is added on top after
    validation.

    Parameters
    ----------
    r_out_idx, r_out_vals : out-of-space residual; r_out_idx sorted ascending
        (as returned by compute_residual_incremental).
    E0 : current variational energy.
    in_space_idx : sorted combined indices of V; ball members in V are dropped.
    n_centers : number of Bruhat-ball centres = top residual determinants.
    h_build_chunk : chunk size handed to build_H_matrix for each block.
    verbose : print per-block diagnostics.

    Returns
    -------
    E_block : float — block-Newton correction.  On a positive-definite
        diagonally-dominant H_N the rigorous ordering (LiH/6-31G machine
        verified, article 10.91 §10) is
            |exact 2nd-order| <= |block| <= |diagonal EN-PT2|,
        i.e. intra-block coupling REDUCES the 2nd-order response, so the
        block value is slightly LESS negative than diagonal PT2 and converges
        to the exact Schur-complement value as the balls cover the normal
        space.  Diagonal EN-PT2 OVER-corrects (its H_DD denominator implicitly
        sums some higher-order terms); this happens to cancel high-order
        error at LARGE residual (small V), but at SMALL residual (near
        convergence, where the stopping decision is made) the unbiased block
        value is strictly more accurate — LiH |V|=488: block/exact-2nd error
        0.0000 mHa vs diagonal 0.0002 mHa (16x).  Inter-block residual is
        ~1e-7 relative (rho(D^-1 O)~0.12-0.17), removable to machine precision
        in 2-3 block-Jacobi sweeps (10.91 §9.1); one block-diagonal pass is
        already far below chemical accuracy for large systems.
    info : dict — n_blocks, block_sizes, n_assigned, residual_coverage
        (fraction of total |r|^2 inside the chosen blocks), block_E per block,
        assigned_idx (sorted global indices), block_members (per-block global
        indices, used to drive block-Jacobi).
    """
    n_out = len(r_out_idx)
    info = {"n_blocks": 0, "block_sizes": [], "block_E": [],
            "n_assigned": 0, "residual_coverage": 0.0,
            "assigned_idx": None, "block_members": []}
    if n_out == 0:
        return 0.0, info

    r_out_idx = np.asarray(r_out_idx)
    r_out_vals = np.asarray(r_out_vals, dtype=float)

    # --- 1. centres = top-n_centers residual determinants (argpartition) ---
    nc = min(n_centers, n_out)
    if n_out > nc:
        centre_sel = np.argpartition(-np.abs(r_out_vals), nc - 1)[:nc]
    else:
        centre_sel = np.arange(nc)
    centres = r_out_idx[centre_sel]

    v_set = set(int(x) for x in np.asarray(in_space_idx)) \
        if in_space_idx is not None else set()
    assigned = set()
    blocks = []

    # --- 2. enumerate each Bruhat 2-ball and assign disjoint members --------
    for C in centres:
        u, _ = apply_H(np.array([1.0 + 0j]), np.array([int(C)]),
                       apply_fn, hd_fn, db, az_of, bz_of, rt_a, rt_b)
        local = [int(x) for x in u.tolist()
                 if x not in v_set and x not in assigned]
        if not local:
            continue
        local = np.unique(np.asarray(local, dtype=np.int64))
        assigned.update(local.tolist())
        blocks.append(local)

    # --- residual-weight coverage of the chosen disjoint blocks ------------
    total_rsq = float(np.sum(r_out_vals ** 2))
    if total_rsq > 0:
        covered = np.array([x for x in r_out_idx.tolist() if x in assigned])
        if len(covered):
            info["residual_coverage"] = float(
                np.sum(_gather_residual(
                    np.unique(covered), r_out_idx, r_out_vals) ** 2)
                / total_rsq)

    # --- 3. per-block dense normal-Hessian inversion ------------------------
    E_block = 0.0
    eye_cache = {}
    for k, local in enumerate(blocks):
        Hb = build_H_matrix(local, apply_fn, hd_fn, db, az_of, bz_of,
                            rt_a, rt_b, H_cols=None, chunk_size=h_build_chunk)
        m = len(local)
        if m not in eye_cache:
            eye_cache[m] = np.eye(m)
        Hn = Hb - E0 * eye_cache[m]
        rb = _gather_residual(local, r_out_idx, r_out_vals)
        # Solve Hn x = rb (Hn real symmetric); robust fallback via eigh if
        # the block is (near-)singular.
        try:
            x = np.linalg.solve(Hn, rb)
        except np.linalg.LinAlgError:
            w, V = np.linalg.eigh(Hn)
            winv = 1.0 / np.where(np.abs(w) < 1e-10, 1e-10, w)
            x = V @ (winv * (V.T @ rb))
        ek = -float(rb @ x)
        E_block += ek
        info["block_sizes"].append(m)
        info["block_E"].append(ek)
        info["block_members"].append(local.copy())
        if verbose:
            print(f"    block {k}: size={m}, E_corr={ek:+.8f}, "
                  f"|r_block|={np.linalg.norm(rb):.6f}")
        del Hb, Hn, rb, x
        import gc; gc.collect()

    info["n_blocks"] = len(blocks)
    info["n_assigned"] = len(assigned)
    info["assigned_idx"] = (np.sort(np.asarray(sorted(assigned),
                                               dtype=np.int64))
                            if assigned else np.array([], dtype=np.int64))
    return E_block, info


# ---------------------------------------------------------------------------
# WCI main iteration
# ---------------------------------------------------------------------------

def wci(apply_fn, hd_fn, seed_idx, db, az_of, bz_of, rt_a, rt_b,
        max_wavepackets=30, tol=1e-6, verbose=True,
        select_weighted=False, hd_full_fn=None, energy_tol=None,
        use_gpu=False, gpu_argsort=None, max_wp_size=None,
        h_build_chunk=500, residual_chunk=80_000_000,
        select_geometric=False, geometric_alpha=1.0,
        select_ball_cover=False, ball_cover_topk=100,
        compute_pt2=False, pt2_top_n=50000, pt2_chunk=200,
        return_final_residual=False):
    """Wavepacket Configuration Interaction.

    Parameters
    ----------
    apply_fn : callable
        The sparse action from exterior.sparse_action_sz (vectorised single
        + double excitations, two-body diagonal included).
    hd_fn : callable
        One-body diagonal lookup (sector_diagonal_sz array for small dim,
        sector_diagonal_at for large dim).  Must have two_body=False.
    seed_idx : int
        The first wavepacket centre (typically the HF determinant).
    db : int
        Beta-sector dimension (combined index = alpha_rank * db + beta_rank).
    az_of, bz_of, rt_a, rt_b : arrays
        Rank tables from build_rank_tables.
    max_wavepackets : int
        Maximum number of wavepackets (iterations).
    tol : float
        Convergence tolerance on out-of-space residual norm (||r_out|| < tol
        AND energy change < tol).  For large systems where residual converges
        much slower than energy, use energy_tol instead.
    energy_tol : float | None
        If set, converge when |ΔE| < energy_tol (energy-change criterion),
        regardless of residual norm.  WCI energy converges much faster than
        residual: for chemical accuracy (1 kcal/mol = 1.59 mHa), use
        energy_tol=1e-4 (0.1 mHa, 16× tighter than chemical precision).
        This avoids the residual-norm bottleneck on large systems (H2O/cc-pVDZ:
        ||r_out||=0.26 at 7 wavepackets but energy already within ~0.6 mHa
        of FCI).
    verbose : bool
        Print per-iteration diagnostics.
    select_weighted : bool
        If True, select the new wavepacket centre by the energy-optimal
        (denominator-weighted) criterion argmax |<D|r>|^2 / |<D|H|D> - E|
        (命题 10.88.3.03/3.04, CIPSI-style) instead of the plain
        argmax |<D|r>|.  Requires hd_full_fn (full diagonal incl. two-body
        and nuclear repulsion).
    hd_full_fn : callable | None
        Full-diagonal lookup hd_full_fn(idxs) -> <D|H|D> (two_body=True),
        used only when select_weighted=True.
    use_gpu : bool
        If True, use GPU-accelerated matvec (OpenCL on AMD RX 570) for
        diagonalization. H matrix is transferred to GPU each iteration.
        2.5-3.0x speedup for V > 5000; slower for small V due to transfer
        overhead. Requires PyOpenCL and an AMD GPU.
    select_geometric : bool
        If True, select the new wavepacket centre by the geometric
        (Bruhat-distance weighted) criterion:
            score(D) = |r_D|^2 / (1 + α · min_{D'∈centres} bruhat_dist(D,D'))
        This penalises candidates that lie close to already-selected centres
        (their Bruhat 2-balls heavily overlap, adding little new information).
        Fixes the "false convergence" problem where CIPSI-style argmax |r_D|
        repeatedly selects overlapping wavepackets.  α=0 recovers plain CIPSI.
    geometric_alpha : float
        Overlap-penalty strength α in the geometric selection criterion
        (only used when select_geometric=True).  Larger α enforces more
        geometric diversity; recommended range 0.5–3.0.  Default 1.0.
    select_ball_cover : bool
        If True, select the new wavepacket centre by the fully-geometric
        Bruhat-ball greedy-cover criterion:
            score(D) = |r_D|^2 * (1 - |B(D,2) ∩ V| / |B(D,2)|)
        where V is the existing variational space.  This picks the Bruhat
        ball covering the largest *uncovered* residual weight, instead of
        CIPSI's argmax |r_D| (pick a point).  This is the geometric cure
        for "false convergence": a point with large residual but lying
        inside an already-covered ball adds little new information; the
        ball-cover score naturally penalises such picks.
        Priority: ball_cover > geometric > weighted > plain.
    ball_cover_topk : int
        Number of top residual candidates to evaluate for ball-cover
        selection (default 100).  Each candidate requires one apply_fn to
        compute its Bruhat ball support; larger top_k is more accurate but
        slower.
    compute_pt2 : bool
        If True, compute Epstein-Nesbet PT2 energy correction after each
        iteration: E_PT2 = sum_{D not in V} |r_D|^2 / (E0 - H_DD).
        This is the diagonal approximation of the geometric normal-Hessian
        correction E_corr = -<r| (P_out H P_out - E0 I)^{-1} |r>.
        PT2 gives a much better estimate of the true correlation energy
        than the variational energy alone, often reaching chemical accuracy
        with far fewer wavepackets.
    pt2_top_n : int
        Number of top residual determinants to evaluate for PT2 (default
        100k).  PT2 is dominated by large residuals; tail contribution is
        negligible.  Larger top_n is more accurate but slower.
    pt2_chunk : int
        apply_fn batch size for PT2 H_DD computation (default 500).
        Smaller chunks avoid output buffer overflow; larger chunks are
        faster but use more memory.

    Returns
    -------
    E : float
        Converged ground-state energy.
    unique_idx : ndarray
        Final variational space (sorted determinant indices).
    coeffs : ndarray
        Ground-state eigenvector coefficients in the variational space.
    wavepackets : list[Wavepacket]
        All wavepackets added during the iteration.
    history : list[tuple]
        (n_var, E, r_in_norm, r_out_norm) per iteration.
    """
    t_start = time.time()
    wavepackets = [Wavepacket(seed_idx, apply_fn, hd_fn, db, az_of, bz_of,
                               rt_a, rt_b, max_size=max_wp_size)]
    if verbose:
        print(f'  WP  1: center={wavepackets[0].center}, '
              f'size={wavepackets[0].size}')

    E_prev = None
    history = []
    H_mat_prev = None
    unique_idx_prev = None
    H_cols = {}  # cached full H|D⟩ columns for incremental residual
    selected_centers = [int(seed_idx)]  # for geometric (Bruhat-distance) selection
    # Last-iteration out-of-space residual (returned when return_final_residual)
    final_r_out_idx = np.array([], dtype=np.int64)
    final_r_out_vals = np.array([], dtype=np.float64)

    for iteration in range(max_wavepackets):
        # 1. variational space (cumulative union of wavepacket supports)
        unique_idx = build_variational_space(wavepackets)
        n_var = len(unique_idx)

        # 2. Rayleigh-Ritz (incremental H build + column caching)
        t0 = time.time()
        if H_mat_prev is not None and unique_idx_prev is not None:
            H_mat = build_H_incremental(
                unique_idx, unique_idx_prev, H_mat_prev,
                apply_fn, hd_fn, db, az_of, bz_of, rt_a, rt_b, H_cols)
        else:
            H_mat = build_H_matrix(
                unique_idx, apply_fn, hd_fn, db, az_of, bz_of, rt_a, rt_b,
                H_cols, chunk_size=h_build_chunk)

        # GPU-accelerated diagonalization (if enabled and V large enough)
        gpu_H = None
        if use_gpu and n_var > DAVIDSON_MIN_DIM:
            try:
                from geoqc.gpu import GPUMatrix
                gpu_H = GPUMatrix(H_mat)
            except Exception as e:
                if verbose:
                    print(f'  [GPU] Falling back to CPU: {e}')
                gpu_H = None

        E, coeffs = _eigh_ground(H_mat, gpu_H=gpu_H)
        if gpu_H is not None:
            gpu_H.release()
        t_h = time.time() - t0

        # 3. residual (incremental: cached column linear combination)
        t0 = time.time()
        r_in_norm, r_out_idx, r_out_vals = compute_residual_incremental(
            coeffs, unique_idx, H_cols, E, gpu_argsort=gpu_argsort,
            residual_chunk=residual_chunk,
            apply_fn=apply_fn, hd_fn=hd_fn, db=db,
            az_of=az_of, bz_of=bz_of, rt_a=rt_a, rt_b=rt_b)
        r_out_norm = (np.linalg.norm(r_out_vals)
                      if len(r_out_vals) > 0 else 0.0)
        # keep the latest out-of-space residual for block-Newton post-pass
        final_r_out_idx = r_out_idx
        final_r_out_vals = r_out_vals
        t_r = time.time() - t0

        # 3b. PT2 energy correction (Epstein-Nesbet, diagonal approximation)
        #     Geometric: normal-Hessian correction on the Grassmannian
        #     E_PT2 = sum |r_D|^2 / (E0 - H_DD) — much better energy estimate
        E_pt2 = 0.0
        E_corrected = E
        if compute_pt2 and len(r_out_vals) > 0:
            t0_pt2 = time.time()
            E_pt2, n_pt2 = compute_pt2_correction(
                r_out_idx, r_out_vals, E, apply_fn, hd_fn, db,
                az_of, bz_of, rt_a, rt_b,
                top_n=pt2_top_n, chunk_size=pt2_chunk)
            E_corrected = E + E_pt2
            t_pt2 = time.time() - t0_pt2
        else:
            t_pt2 = 0.0
            n_pt2 = 0

        history.append((n_var, E, r_in_norm, r_out_norm))
        if verbose:
            pt2_str = (f'  E+PT2={E_corrected:.10f} (PT2={E_pt2:+.6f}, '
                        f'n={n_pt2}, {t_pt2:.1f}s)' if compute_pt2 else '')
            print(f'  iter {iteration+1:2d}: n_var={n_var:7d}  '
                  f'E={E:.10f}  ||r_in||={r_in_norm:.2e}  '
                  f'||r_out||={r_out_norm:.2e}  n_wp={len(wavepackets)}  '
                  f'H={t_h:.1f}s  r={t_r:.1f}s{pt2_str}')

        # 4. convergence check
        if E_prev is not None:
            dE = abs(E - E_prev)
            # Energy-change criterion (fast): converge when |ΔE| < energy_tol,
            # regardless of residual norm.  WCI energy converges much faster
            # than ||r_out|| on large systems.
            if energy_tol is not None and dE < energy_tol:
                if verbose:
                    print(f'  Converged (energy) at iter {iteration+1}: '
                          f'|ΔE|={dE:.2e} < {energy_tol:.2e}')
                break
            # Residual criterion (strict): both |ΔE| < tol and ||r_out|| < tol
            if dE < tol and r_out_norm < tol:
                if verbose:
                    print(f'  Converged at iter {iteration+1}')
                break
        E_prev = E
        H_mat_prev = H_mat
        unique_idx_prev = unique_idx
        if iteration == max_wavepackets - 1:
            break

        # 5. new wavepacket centre selection.
        #    Four criteria (priority: ball_cover > geometric > weighted > plain):
        #    (a) select_ball_cover: Bruhat-ball greedy-cover (FULLY GEOMETRIC)
        #        score(D) = |r_D|^2 * (1 - |B(D,2) ∩ V| / |B(D,2)|)
        #        — pick the ball covering the largest *uncovered* residual weight;
        #          the geometric cure for CIPSI's false convergence.
        #    (b) select_geometric: Bruhat-distance weighted score
        #        score(D) = |r_D|^2 / (1 + α · min bruhat_dist(D, centres))
        #        — penalises overlap with existing wavepackets (approximate);
        #    (c) select_weighted: denominator-weighted (CIPSI PT2 style)
        #        score(D) = |r_D|^2 / |H_DD - E|;
        #    (d) plain: argmax |r_D| (default, CIPSI-style).
        if len(r_out_vals) > 0:
            if select_ball_cover:
                # Fully-geometric Bruhat-ball greedy-cover selection
                t_sel = time.time()
                new_center, best_score, best_local = _ball_cover_select(
                    r_out_idx, np.abs(r_out_vals), apply_fn, unique_idx,
                    db, az_of, bz_of, rt_a, rt_b,
                    top_k=ball_cover_topk, batch_size=50)
                # Find the index in r_out_idx for verbose output
                best = int(np.where(r_out_idx == new_center)[0][0]) \
                    if np.any(r_out_idx == new_center) else 0
                if verbose:
                    print(f'  [ball_cover] top_k={ball_cover_topk}, '
                          f'score={best_score:.3e}, '
                          f'|r|={abs(r_out_vals[best]):.2e}, '
                          f'sel_time={time.time()-t_sel:.1f}s')
            elif select_geometric:
                # Geometric (Bruhat-distance weighted) selection
                r_sq = np.abs(r_out_vals) ** 2
                min_dist = _bruhat_dist_vec(
                    r_out_idx, np.array(selected_centers, dtype=np.int64),
                    db, az_of, bz_of)
                score = r_sq / (1.0 + geometric_alpha * min_dist.astype(float))
                best = int(np.argmax(score))
                new_center = int(r_out_idx[best])
                if verbose:
                    print(f'  [geometric] best |r|={abs(r_out_vals[best]):.2e}, '
                          f'min_bruhat_dist={min_dist[best]}, '
                          f'α={geometric_alpha}')
            elif select_weighted and hd_full_fn is not None:
                denom = hd_full_fn(r_out_idx) - E
                score = np.abs(r_out_vals) ** 2 / np.maximum(np.abs(denom),
                                                             1e-10)
                best = int(np.argmax(score))
                new_center = int(r_out_idx[best])
            else:
                best = int(np.argmax(np.abs(r_out_vals)))
                new_center = int(r_out_idx[best])
            selected_centers.append(new_center)
            new_wp = Wavepacket(new_center, apply_fn, hd_fn, db, az_of,
                                 bz_of, rt_a, rt_b, max_size=max_wp_size)
            wavepackets.append(new_wp)
            if verbose:
                print(f'  WP {len(wavepackets):2d}: center={new_center}, '
                      f'size={new_wp.size}, |r|={abs(r_out_vals[best]):.2e}')
        else:
            if verbose:
                print('  No residual outside space — fully converged')
            break

    if verbose:
        print(f'  WCI done in {time.time()-t_start:.1f}s: '
              f'n_wp={len(wavepackets)}, n_var={len(unique_idx)}, '
              f'E={E:.10f}')
    if return_final_residual:
        # extra final out-of-space residual for a geometric block-Newton
        # (10.91 §6) post-pass without recomputing H columns.
        return (E, unique_idx, coeffs, wavepackets, history,
                final_r_out_idx, final_r_out_vals)
    return E, unique_idx, coeffs, wavepackets, history

"""Wavepacket Configuration Interaction (WCI) — the geometrised FCI solver.

Based on the machine-verified wavepacket model (article 10.87 §6.03-05):
  - the ground state is a superposition of a small number (1-5 for STO-3G,
    ~10 for 6-31G chemical accuracy) of localised wavepackets on the
    Grassmannian;
  - a wavepacket = a centre determinant + its Bruhat 2-neighbourhood (all
    1-2 excitations, generated by H·centre);
  - the number of wavepackets grows sub-linearly with sector dimension
    (∝ log dim), far below the linear scaling of top-k power iteration.

Core algorithm (selected CI, wavepacket version):
  1. seed: the HF determinant as the first wavepacket centre;
  2. variational space = union of all wavepacket supports (cumulative,
     Bruhat-connected, only grows);
  3. Rayleigh-Ritz: build the dense H matrix in the variational space and
     diagonalise (the variational principle guarantees monotone convergence);
  4. residual r = H|ψ⟩ - E|ψ⟩;
  5. new wavepacket centre = the determinant outside the variational space
     with the largest residual component;
  6. repeat until converged.

Essential difference from top-k power iteration:
  - top-k re-selects k largest components each iteration; the support is
    unstructured and may split wavepackets, risking convergence to a wrong
    state;
  - WCI grows the variational space cumulatively (only adds, never removes);
    each added unit is a Bruhat-connected wavepacket.

Performance layers (verified on LiH/6-31G, dim=3025):
  1. searchsorted replaces dict lookup in H-matrix fill;
  2. incremental H-matrix build (reuse old block, only apply new states);
  3. float64 instead of complex128 (real-basis integrals → real symmetric
     H; eigh is ~17× faster on real symmetric matrices);
  4. incremental residual via cached H columns (H|D⟩ stored at H-build time,
     residual = column linear combination, no apply_fn Python loops);
  5. vectorised single-excitation enumeration in exterior.sparse_action_sz
     (precomputed term arrays replace the per-state Python nested loop).

Total speedup: 175s → 7.6s (23×) on LiH/6-31G.

Honest boundaries:
  - the SCF integrals are physical input (pyscf), not re-derived by geometry;
  - FCI reference energies are independent verification benchmarks;
  - the wavepacket model is empirically verified on four molecular systems
    (H₂/STO-3G, LiH/STO-3G, H₂O/STO-3G, LiH/6-31G); a formal proof of the
    sub-linear wavepacket scaling is an open geometric question.
"""

import time
import numpy as np
from itertools import combinations
from math import comb

try:
    from scipy.sparse.linalg import eigsh, LinearOperator
    _HAS_SCIPY = True
except ImportError:
    _HAS_SCIPY = False

# Threshold below which dense eigh is faster than Davidson (overhead of
# iterative method dominates for small matrices).
DAVIDSON_MIN_DIM = 300


# ---------------------------------------------------------------------------
# Geometric (Bruhat-distance) wavepacket centre selection
# ---------------------------------------------------------------------------
# The CIPSI-style "argmax |r_D|" selects the single determinant with the
# largest residual, but this determinant may lie inside the Bruhat 2-ball
# of an already-selected centre — the new wavepacket then heavily overlaps
# the existing one and adds little new information ("false convergence").
#
# Geometric cure: penalise candidates by their minimum Bruhat distance to
# already-selected centres.  Two determinants have Bruhat distance equal to
# the minimum number of excitations connecting them = popcount(az XOR) / 2
# + popcount(bz XOR) / 2.  Small distance ⇒ B(D,2) balls heavily overlap
# ⇒ low marginal information; large distance ⇒ complementary coverage.
#
# score(D) = |r_D|^2 / (1 + α · min_{D'∈centres} bruhat_dist(D, D'))
#
# This is a determinantal-point-process-style repulsive selection: the
# numerator keeps CIPSI's residual relevance, the denominator enforces
# geometric diversity.  α=0 recovers plain CIPSI; α→∞ enforces maximum
# diversity regardless of residual.

def _bruhat_dist_vec(cand_idx, center_idx, db, az_of, bz_of):
    """Vectorised minimum Bruhat distance from each candidate to any centre.

    Parameters
    ----------
    cand_idx : (M,) int array — candidate determinant combined indices
    center_idx : (K,) int array — already-selected centre combined indices
    db : int — beta-sector dimension (combined = alpha_rank * db + beta_rank)
    az_of, bz_of : arrays — rank → bitstring lookup tables

    Returns
    -------
    min_dist : (M,) int array — minimum Bruhat distance from each candidate
                to any centre (0 if candidate equals a centre).
    """
    if len(center_idx) == 0:
        return np.zeros(len(cand_idx), dtype=np.int64)
    # candidate bitstrings
    c_az = az_of[cand_idx // db]
    c_bz = bz_of[cand_idx % db]
    # centre bitstrings
    k_az = az_of[center_idx // db]
    k_bz = bz_of[center_idx % db]
    # For each candidate, compute min over centres of bruhat distance.
    # bruhat_dist = popcount(az_xor)//2 + popcount(bz_xor)//2
    # = (popcount(az_xor) + popcount(bz_xor)) // 2
    min_dist = np.full(len(cand_idx), 999, dtype=np.int64)
    for k in range(len(center_idx)):
        xor_az = c_az ^ k_az[k]
        xor_bz = c_bz ^ k_bz[k]
        # popcount via numpy (uint64 bit_count available in numpy 2.0+)
        try:
            pc_az = np.bitwise_count(xor_az.astype(np.uint64))
            pc_bz = np.bitwise_count(xor_bz.astype(np.uint64))
        except AttributeError:
            # fallback for older numpy
            pc_az = np.array([bin(int(x)).count('1') for x in xor_az], dtype=np.int64)
            pc_bz = np.array([bin(int(x)).count('1') for x in xor_bz], dtype=np.int64)
        dist = (pc_az + pc_bz) // 2
        min_dist = np.minimum(min_dist, dist)
    return min_dist


def _ball_cover_select(cand_idx, cand_r, apply_fn, unique_idx, db,
                       az_of, bz_of, rt_a, rt_b, top_k=100, batch_size=50):
    """Bruhat-ball greedy-cover wavepacket centre selection.

    Geometric cure for CIPSI's "false convergence": instead of argmax |r_D|
    (pick a *point*), pick the Bruhat ball B(D,2) that covers the largest
    *uncovered* residual weight.  A point with large residual but lying
    inside an already-covered ball adds little new information; the
    ball-cover score naturally penalises such picks.

    Algorithm:
      1. Take top-K candidates by |r_D|
      2. Batch apply_fn to get B(D,2) support for all candidates (in batches
         of batch_size to respect apply_fn's output buffer limit)
      3. For each ball, compute intersection with existing variational space
         via searchsorted
      4. uncovered_fraction = 1 - intersection / ball_size
      5. score(D) = |r_D|^2 * uncovered_fraction
      6. Return the candidate with max score

    Parameters
    ----------
    cand_idx : (M,) int array — candidate centre combined indices
    cand_r : (M,) float array — residual values at candidates
    apply_fn : callable — sparse_action_sz_vec apply function
    unique_idx : (V,) int array — existing variational space (sorted)
    db : int — beta-sector dimension
    az_of, bz_of, rt_a, rt_b : rank tables
    top_k : int — number of top candidates to consider (default 100)
    batch_size : int — apply_fn batch size (default 50, ~4M outputs/batch)

    Returns
    -------
    best_center : int — combined index of the selected centre
    best_score : float — ball-cover score of the selected centre
    best_local_idx : int — index in the top-K candidate list
    """
    import gc as _gc

    # 1. Take top-K candidates by |r_D|
    if len(cand_idx) > top_k:
        top_k_idx = np.argsort(-np.abs(cand_r))[:top_k]
        cand_idx = cand_idx[top_k_idx]
        cand_r = cand_r[top_k_idx]

    n_cand = len(cand_idx)
    scores = np.zeros(n_cand)
    ball_sizes = np.zeros(n_cand, dtype=np.int64)
    intersections = np.zeros(n_cand, dtype=np.int64)

    # 2. Batch apply_fn to get B(D,2) support
    for b0 in range(0, n_cand, batch_size):
        b1 = min(b0 + batch_size, n_cand)
        batch_cand = cand_idx[b0:b1]
        azs = az_of[batch_cand // db]
        bzs = bz_of[batch_cand % db]
        vals = np.ones(len(batch_cand), dtype=complex)
        result = apply_fn(azs, bzs, vals)
        if len(result) != 4:
            # fallback: plain CIPSI for this batch
            for i in range(b0, b1):
                scores[i] = abs(cand_r[i]) ** 2
            continue
        t_az, t_bz, t_v, src_idx = result
        # Convert target bitstrings to combined indices
        t_idx = rt_a.rank(t_az) * db + rt_b.rank(t_bz)
        del t_az, t_bz, t_v

        # 3. Group by local source index (0..batch_size-1)
        for local_s in range(len(batch_cand)):
            mask = src_idx == local_s
            ball_idx = t_idx[mask]
            ball_size = len(ball_idx)
            if ball_size == 0:
                continue
            global_i = b0 + local_s
            ball_sizes[global_i] = ball_size
            # Intersection with existing variational space via searchsorted
            pos = np.searchsorted(unique_idx, ball_idx)
            valid = pos < len(unique_idx)
            if valid.any():
                valid[valid] &= unique_idx[pos[valid]] == ball_idx[valid]
            inter = int(np.sum(valid))
            intersections[global_i] = inter
            uncovered_frac = 1.0 - inter / ball_size
            scores[global_i] = (abs(cand_r[global_i]) ** 2) * uncovered_frac

        del t_idx, src_idx, result
        _gc.collect()

    best_local = int(np.argmax(scores))
    best_center = int(cand_idx[best_local])
    best_score = float(scores[best_local])
    return best_center, best_score, best_local


def _davidson_ground(H_mat, tol=1e-8, max_iter=60, max_vecs=40):
    """Diagonally-preconditioned Davidson for the ground state.

    Much faster than implicitly-restarted Lanczos (scipy eigsh) for
    diagonally-dominant quantum-chemistry H matrices: the diagonal
    preconditioner t = -r / (H_ii - theta) gives far better correction
    directions than Lanczos' Krylov expansion, typically converging in
    10-20 matvecs vs 100+ for Lanczos.

    Algorithm:
      1. Start with orthonormal subspace V (random initial vectors)
      2. Project: T = V^T H V, diagonalise -> Ritz pairs (theta, s)
      3. Residual: r = H(Vs) - theta(Vs)
      4. Precondition: t = -r / (diag(H) - theta)
      5. Orthogonalise t against V, append to subspace
      6. Restart when subspace exceeds max_vecs (keep lowest Ritz vectors)
      7. Repeat until ||r|| < tol

    Parameters
    ----------
    H_mat : ndarray, shape (V, V)
        Real symmetric Hamiltonian matrix.
    tol : float
        Convergence tolerance on residual norm.
    max_iter : int
        Maximum Davidson iterations.
    max_vecs : int
        Maximum subspace size before restart.

    Returns
    -------
    E0 : float
        Ground-state energy.
    c0 : ndarray, shape (V,)
        Ground-state eigenvector.
    """
    V = H_mat.shape[0]
    h_diag = np.diag(H_mat)

    # Initial subspace: 3 random orthonormal vectors (seeded for reproducibility)
    rng = np.random.default_rng(42)
    n_init = min(3, V)
    V_vecs = rng.standard_normal((V, n_init))
    for i in range(n_init):
        for j in range(i):
            V_vecs[:, i] -= V_vecs[:, j] * (V_vecs[:, j] @ V_vecs[:, i])
        norm = np.linalg.norm(V_vecs[:, i])
        V_vecs[:, i] /= norm if norm > 1e-10 else 1.0

    HV = H_mat @ V_vecs  # precompute H*V (matvecs counted here)

    for iteration in range(max_iter):
        m = V_vecs.shape[1]
        # Projected Hamiltonian (small m×m, cheap)
        T = V_vecs.T @ HV
        theta, s = np.linalg.eigh(T)
        theta0 = float(theta[0])
        s0 = s[:, 0]

        # Ritz vector and residual (no extra matvec: HV = H*V)
        u = V_vecs @ s0
        r = HV @ s0 - theta0 * u
        r_norm = np.linalg.norm(r)

        if r_norm < tol:
            return theta0, u

        # Diagonal preconditioning (the key Davidson ingredient)
        denom = h_diag - theta0
        denom = np.where(np.abs(denom) < 1e-10, 1e-10, denom)
        t = -r / denom

        # Orthogonalise against current subspace (Modified Gram-Schmidt)
        for j in range(m):
            t -= V_vecs[:, j] * (V_vecs[:, j] @ t)
        t_norm = np.linalg.norm(t)
        if t_norm < 1e-10:
            # Fallback: random direction if preconditioned vector is in subspace
            t = rng.standard_normal(V)
            for j in range(m):
                t -= V_vecs[:, j] * (V_vecs[:, j] @ t)
            t_norm = np.linalg.norm(t)
            if t_norm < 1e-10:
                break
        t /= t_norm

        # Expand subspace
        V_vecs = np.hstack([V_vecs, t.reshape(-1, 1)])
        Ht = H_mat @ t  # one matvec per iteration
        HV = np.hstack([HV, Ht.reshape(-1, 1)])

        # Restart if subspace too large: keep lowest n_keep Ritz vectors
        if V_vecs.shape[1] > max_vecs:
            # Recompute projection with expanded subspace (after adding t)
            T = V_vecs.T @ HV
            theta_r, s_r = np.linalg.eigh(T)
            n_keep = max(10, max_vecs // 2)
            V_new = V_vecs @ s_r[:, :n_keep]
            HV_new = HV @ s_r[:, :n_keep]
            # Re-orthonormalise
            for i in range(n_keep):
                for j in range(i):
                    V_new[:, i] -= V_new[:, j] * (V_new[:, j] @ V_new[:, i])
                norm = np.linalg.norm(V_new[:, i])
                V_new[:, i] /= norm if norm > 1e-10 else 1.0
            V_vecs = V_new
            HV = HV_new

    # Final best estimate
    m = V_vecs.shape[1]
    T = V_vecs.T @ HV
    theta, s = np.linalg.eigh(T)
    u = V_vecs @ s[:, 0]
    return float(theta[0]), u


def _eigh_ground(H_mat, k=3, tol=1e-8, v0=None, gpu_H=None):
    """Ground-state eigenpair of a real symmetric H matrix.

    Uses scipy.sparse.linalg.eigsh (implicitly restarted Lanczos) for
    large matrices (V > DAVIDSON_MIN_DIM), falling back to dense
    np.linalg.eigh for small matrices where Lanczos overhead dominates.

    This replaces the O(V^3) dense diagonalisation with O(V^2 * n_iter)
    iterative diagonalisation — the single largest optimisation in WCI
    (profiling: dense eigh = 75% of total time on LiH/6-31G, V=1511).

    Parameters
    ----------
    H_mat : ndarray, shape (V, V)
        Real symmetric Hamiltonian matrix in the variational space.
    k : int
        Number of eigenpairs requested (must be < V-1 for eigsh).
    tol : float
        Convergence tolerance for eigsh.
    v0 : ndarray | None
        Initial guess vector for eigsh.
    gpu_H : GPUMatrix | None
        If provided, use GPU-accelerated matvec instead of H_mat @ x.
        H_mat is still needed for small-matrix fallback and shape info.

    Returns
    -------
    E0 : float
        Ground-state energy.
    c0 : ndarray, shape (V,)
        Ground-state eigenvector.
    """
    V = H_mat.shape[0]
    if not _HAS_SCIPY or V <= DAVIDSON_MIN_DIM:
        E_all, vecs = np.linalg.eigh(H_mat)
        return float(E_all[0]), vecs[:, 0]

    k_eff = min(k, V - 2)
    if gpu_H is not None:
        H_op = gpu_H.as_linear_operator()
    else:
        H_op = LinearOperator((V, V), matvec=lambda x: H_mat @ x, dtype=float)
    ncv = min(20, V)
    if v0 is None or len(v0) != V:
        v0 = np.ones(V) / np.sqrt(V)
    E, vecs = eigsh(H_op, k=k_eff, which='SA', tol=tol, v0=v0, ncv=ncv)
    idx = np.argmin(E)
    return float(E[idx]), vecs[:, idx]


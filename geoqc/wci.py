# ---------------------------------------------------------------------------
# Rank tables (S_z sector: alpha/beta bitstring ↔ combined index)
# ---------------------------------------------------------------------------

def build_rank_tables(n_orb, n_a, n_b, da, db):
    """(rt_a, rt_b, az_of, bz_of) — the index maps for the S_z sector.

    rt_a[az] = alpha rank (or -1 if az has wrong popcount),
    rt_b[bz] = beta rank,
    az_of[i]  = alpha bitstring of rank i,
    bz_of[j]  = beta bitstring of rank j.
    Combined index = rt_a[az] * db + rt_b[bz]."""
    rt_a = np.full(1 << n_orb, -1, dtype=np.int64)
    rt_b = np.full(1 << n_orb, -1, dtype=np.int64)
    for i, c in enumerate(combinations(range(n_orb), n_a)):
        rt_a[sum(1 << j for j in c)] = i
    for i, c in enumerate(combinations(range(n_orb), n_b)):
        rt_b[sum(1 << j for j in c)] = i
    az_of = np.full(da, -1, dtype=np.int64)
    bz_of = np.full(db, -1, dtype=np.int64)
    for i, c in enumerate(combinations(range(n_orb), n_a)):
        az_of[i] = sum(1 << j for j in c)
    for i, c in enumerate(combinations(range(n_orb), n_b)):
        bz_of[i] = sum(1 << j for j in c)
    return rt_a, rt_b, az_of, bz_of


# ---------------------------------------------------------------------------
# Full H|ψ⟩ = apply (excitations + two-body diagonal) + hd_fn (one-body diag)
# ---------------------------------------------------------------------------

def apply_H(vals, idx, apply_fn, hd_fn, db, az_of, bz_of, rt_a, rt_b):
    """Full H|ψ⟩ on an arbitrary small support, returns (unique_target_idx,
    merged_vals).

    apply_fn gives the excitation terms (single/double) plus the two-body
    diagonal contribution; hd_fn gives the one-body diagonal.  The two are
    added on the unique target set.  Real-basis integrals → float64 output
    (eigh on real symmetric H is ~17× faster than complex Hermitian)."""
    azs = az_of[idx // db]
    bzs = bz_of[idx % db]
    result = apply_fn(azs, bzs, vals)
    if len(result) == 4:
        t_az, t_bz, t_v, _ = result  # vectorised version returns src_idx too
    else:
        t_az, t_bz, t_v = result
    t_idx = rt_a[t_az] * db + rt_b[t_bz]
    all_idx = np.concatenate([t_idx, idx])
    all_v = np.concatenate([np.asarray(t_v).real,
                             np.asarray(hd_fn(idx) * vals).real])
    u, inv = np.unique(all_idx, return_inverse=True)
    w = np.zeros(len(u), dtype=float)
    np.add.at(w, inv, all_v)
    return u, w


# ---------------------------------------------------------------------------
# Wavepacket
# ---------------------------------------------------------------------------

class Wavepacket:
    """A Bruhat 2-neighbourhood wavepacket centred at center_idx.

    Support = {centre} ∪ {all targets of apply(centre)} (1-2 excitations +
    two-body diagonal targets).  Because H is a 1+2-body operator, the
    targets of apply(centre) are exactly the states at Bruhat distance ≤ 2.

    couplings[D] = H_{D, centre} (the full diagonal of the centre is
    included as couplings[centre])."""

    def __init__(self, center_idx, apply_fn, hd_fn, db, az_of, bz_of,
                 rt_a, rt_b, max_size=None):
        self.center = int(center_idx)
        u, w = apply_H(np.array([1.0 + 0j]), np.array([self.center]),
                        apply_fn, hd_fn, db, az_of, bz_of, rt_a, rt_b)
        # Truncate to max_size strongest couplings if specified (large systems)
        if max_size is not None and len(u) > max_size:
            order = np.argsort(-np.abs(w))[:max_size]
            u = u[order]
            w = w[order]
        self.support = u
        self.size = len(u)
        self.couplings = dict(zip(u.tolist(), w.tolist()))

    def full_diagonal(self, state_idx):
        """Full diagonal E_D = H_{D,D} of the centre or a support state."""
        return self.couplings.get(int(state_idx), 0.0)


# ---------------------------------------------------------------------------
# Variational space and H matrix
# ---------------------------------------------------------------------------

def build_variational_space(wavepackets):
    """Union of all wavepacket supports, sorted and deduplicated."""
    all_idx = np.concatenate([wp.support for wp in wavepackets])
    return np.unique(all_idx)


def build_H_matrix(unique_idx, apply_fn, hd_fn, db, az_of, bz_of, rt_a,
                   rt_b, H_cols=None, chunk_size=500):
    """Memory-optimised H-matrix construction with chunked batch apply.

    Each chunk's apply_fn output is immediately written into H_mat and
    H_cols, then freed — peak memory is O(n^2) for the H matrix itself,
    not O(total_output_terms).  This avoids the OOM/swap timeout seen at
    >5000 states (2.4M output terms × 24 bytes ≈ 60GB peak).

    If H_cols is provided, the full column H|D_j⟩ (including out-of-space
    targets) is cached per-source for the incremental residual.

    Returns the dense real symmetric H matrix."""
    n = len(unique_idx)
    H_mat = np.zeros((n, n), dtype=float)

    # ---- chunked batch apply: fill H_mat per-chunk and free ----
    for c0 in range(0, n, chunk_size):
        c1 = min(c0 + chunk_size, n)
        chunk_idx = unique_idx[c0:c1]
        azs = az_of[chunk_idx // db]
        bzs = bz_of[chunk_idx % db]
        vals = np.ones(c1 - c0, dtype=complex)
        result = apply_fn(azs, bzs, vals)
        if len(result) == 4:
            t_az, t_bz, t_v, src_idx = result
        else:
            # fallback: scalar apply_fn (no src_idx) — process per-state
            from scipy.sparse import coo_matrix
            H_mat = np.zeros((n, n), dtype=float)
            for j in range(n):
                u, w = apply_H(np.array([1.0+0j]), np.array([unique_idx[j]]),
                               apply_fn, hd_fn, db, az_of, bz_of, rt_a, rt_b)
                if H_cols is not None:
                    H_cols[int(unique_idx[j])] = (u, w)
                pos = np.searchsorted(unique_idx, u)
                valid = pos < n
                if valid.any():
                    valid[valid] &= unique_idx[pos[valid]] == u[valid]
                np.add.at(H_mat, (pos[valid], j), w[valid])
            H_mat = (H_mat + H_mat.conj().T) / 2.0
            return H_mat

        t_idx = rt_a[t_az] * db + rt_b[t_bz]
        t_v = np.asarray(t_v).real
        src_global = src_idx + c0  # adjust to global source index

        # ---- fill H_mat for this chunk ----
        col_pos = src_global
        row_pos = np.searchsorted(unique_idx, t_idx)
        valid = row_pos < n
        if valid.any():
            valid[valid] &= unique_idx[row_pos[valid]] == t_idx[valid]
        np.add.at(H_mat, (row_pos[valid], col_pos[valid]), t_v[valid])

        # ---- cache H_cols for this chunk ----
        if H_cols is not None:
            order = np.argsort(src_global, kind='stable')
            s_src = src_global[order]
            s_idx = t_idx[order]
            s_v = t_v[order]
            # Filter: keep targets with |value| > threshold (both in-space and out-of-space)
            # This filters ~80% of tiny coefficients while preserving all significant couplings
            # for residual calculation (no need to recompute out-of-space residual)
            _sig = np.abs(s_v) > 1e-5
            s_idx = s_idx[_sig]
            s_v = s_v[_sig]
            s_src = s_src[_sig]
            boundaries = np.where(np.diff(s_src) != 0)[0] + 1
            starts = np.concatenate([[0], boundaries])
            ends = np.concatenate([boundaries, [len(s_src)]])
            for si in range(len(starts)):
                src = int(s_src[starts[si]])
                # Store copies (not views) so per-chunk arrays can be freed
                H_cols[int(unique_idx[src])] = (
                    s_idx[starts[si]:ends[si]].copy(),
                    s_v[starts[si]:ends[si]].copy())

        # free ALL temporary arrays for this chunk
        del t_az, t_bz, t_v, src_idx, t_idx, result, row_pos, valid
        del col_pos, src_global, chunk_idx, azs, bzs, vals
        if H_cols is not None:
            del order, s_src, s_idx, s_v, _sig
            del boundaries, starts, ends
        import gc; gc.collect()

    # ---- add diagonal terms (one-body + nuc; apply_fn gives two-body diag) ----
    diag_vals = np.asarray(hd_fn(unique_idx)).real
    np.add.at(H_mat, (np.arange(n), np.arange(n)), diag_vals)

    # ---- add diagonal to H_cols (one-body + nuc) ----
    if H_cols is not None:
        for j in range(n):
            key = int(unique_idx[j])
            if key in H_cols:
                prev_idx, prev_v = H_cols[key]
                H_cols[key] = (np.concatenate([prev_idx, [key]]),
                               np.concatenate([prev_v, [diag_vals[j]]]))
            else:
                H_cols[key] = (np.array([key], dtype=np.int64),
                               np.array([diag_vals[j]], dtype=float))

    # symmetrise (H is real symmetric; batch fill may have slight asymmetry
    # due to floating-point ordering of duplicate (row,col) entries)
    H_mat = (H_mat + H_mat.conj().T) / 2.0
    return H_mat


def build_H_incremental(unique_idx, unique_idx_prev, H_mat_prev,
                        apply_fn, hd_fn, db, az_of, bz_of, rt_a, rt_b,
                        H_cols=None, chunk_size=200):
    """Memory-optimised incremental H-matrix construction with chunked batch apply.

    Newly-added states are processed in chunks (like build_H_matrix) to avoid
    the OOM caused by a single apply_fn call over thousands of states
    (5000 states × 50k outputs = 250M terms = 6GB in one call).

    H_cols stores copies (not views) of |v|>1e-5 targets for both in-space
    and out-of-space couplings, enabling fast residual calculation without
    recomputing apply_fn."""
    import gc
    n = len(unique_idx)
    new_mask = ~np.isin(unique_idx, unique_idx_prev)
    new_positions = np.where(new_mask)[0]
    m = len(new_positions)
    if m == 0:
        return H_mat_prev

    H_mat = np.zeros((n, n), dtype=float)
    old_positions = np.where(~new_mask)[0]
    H_mat[np.ix_(old_positions, old_positions)] = H_mat_prev

    new_idx = unique_idx[new_positions]

    # ---- chunked batch apply for new states (avoids OOM) ----
    for c0 in range(0, m, chunk_size):
        c1 = min(c0 + chunk_size, m)
        chunk_new_idx = new_idx[c0:c1]
        chunk_positions = new_positions[c0:c1]
        azs = az_of[chunk_new_idx // db]
        bzs = bz_of[chunk_new_idx % db]
        vals = np.ones(c1 - c0, dtype=complex)
        result = apply_fn(azs, bzs, vals)
        if len(result) == 4:
            t_az, t_bz, t_v, src_idx = result
        else:
            t_az, t_bz, t_v = result
            src_idx = np.repeat(np.arange(c1 - c0, dtype=np.int32),
                                 np.array([len(t_az) // (c1 - c0)] * (c1 - c0)))

        t_idx = rt_a[t_az] * db + rt_b[t_bz]
        t_v = np.asarray(t_v).real
        src_global = src_idx.astype(np.int64) + c0  # index into new_idx

        # ---- fill H_mat columns for this chunk ----
        col_pos = new_positions[src_global]
        row_pos = np.searchsorted(unique_idx, t_idx)
        valid = row_pos < n
        if valid.any():
            valid[valid] &= unique_idx[row_pos[valid]] == t_idx[valid]
        np.add.at(H_mat, (row_pos[valid], col_pos[valid]), t_v[valid])

        # ---- cache H_cols for this chunk (|v|>1e-5, copies not views) ----
        if H_cols is not None:
            _sig = np.abs(t_v) > 1e-5
            _s_idx = t_idx[_sig]
            _s_v = t_v[_sig]
            _s_src = src_global[_sig]
            order = np.argsort(_s_src, kind='stable')
            _s_src = _s_src[order]
            _s_idx = _s_idx[order]
            _s_v = _s_v[order]
            boundaries = np.where(np.diff(_s_src) != 0)[0] + 1
            starts = np.concatenate([[0], boundaries])
            ends = np.concatenate([boundaries, [len(_s_src)]])
            for si in range(len(starts)):
                src = int(_s_src[starts[si]])
                H_cols[int(new_idx[src])] = (
                    _s_idx[starts[si]:ends[si]].copy(),
                    _s_v[starts[si]:ends[si]].copy())
            del _sig, _s_idx, _s_v, _s_src, order, boundaries, starts, ends

        # free temporary arrays for this chunk
        del t_az, t_bz, t_v, src_idx, t_idx, result, row_pos, valid
        del col_pos, src_global, chunk_new_idx, chunk_positions, azs, bzs, vals
        gc.collect()

    # ---- add diagonal terms for new states (one-body + nuc) ----
    diag_vals = np.asarray(hd_fn(new_idx)).real
    np.add.at(H_mat, (new_positions, new_positions), diag_vals)

    # ---- add diagonal to H_cols ----
    if H_cols is not None:
        for j in range(m):
            key = int(new_idx[j])
            if key in H_cols:
                prev_idx, prev_v = H_cols[key]
                H_cols[key] = (np.concatenate([prev_idx, [key]]),
                               np.concatenate([prev_v, [diag_vals[j]]]))
            else:
                H_cols[key] = (np.array([key], dtype=np.int64),
                               np.array([diag_vals[j]], dtype=float))

    # fill new rows from new columns by Hermiticity
    H_mat[new_positions, :] = H_mat[:, new_positions].conj().T
    return H_mat



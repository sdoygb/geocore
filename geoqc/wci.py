def compute_residual(coeffs, unique_idx, E, apply_fn, hd_fn, db,
                     az_of, bz_of, rt_a, rt_b):
    """Vectorised residual r = H|ψ⟩ - E|ψ⟩ (searchsorted, no dict lookup).

    Returns (r_in_norm, r_out_idx, r_out_vals) where r_in is the component
    inside the variational space and r_out is the component outside."""
    u, w = apply_H(coeffs, unique_idx, apply_fn, hd_fn, db,
                    az_of, bz_of, rt_a, rt_b)
    n = len(unique_idx)
    pos = np.searchsorted(unique_idx, u)
    in_space = pos < n
    if in_space.any():
        in_space[in_space] &= unique_idx[pos[in_space]] == u[in_space]

    r_in_norm_sq = 0.0
    if in_space.any():
        r_vals = w[in_space] - E * coeffs[pos[in_space]]
        r_in_norm_sq = float(np.sum(np.abs(r_vals) ** 2))

    out_mask = ~in_space
    r_out_idx = u[out_mask]
    r_out_vals = w[out_mask]

    return np.sqrt(r_in_norm_sq), r_out_idx, r_out_vals


def compute_residual_incremental(coeffs, unique_idx, H_cols, E, gpu_argsort=None,
                                  residual_chunk=50_000_000,
                                  apply_fn=None, hd_fn=None, db=None,
                                  az_of=None, bz_of=None, rt_a=None, rt_b=None):
    """Incremental residual via cached H columns, optimized pre-allocated chunked processing.

    H_cols[D] = (target_idx, value) stores the in-space H|D⟩ targets, cached at
    H-matrix construction time.  The in-space residual is a column linear
    combination merged with numpy concatenate + argsort + reduceat.

    If apply_fn is provided, out-of-space targets are recomputed via apply_fn
    (H_cols only caches in-space targets to save memory; ~90% of targets are
    out-of-space for small variational spaces).

    [优化三] 分块残差计算（chunked residual）：
    - 大系统（n_orb=44）4000 态 × 5.3万输出 = 2.13亿元素，超过 GPU argsort max_n
    - 将态分成小块，每块输出 < residual_chunk，分别用 GPU argsort + reduceat 合并
    - 收集各块合并结果后，最终再合并一次（唯一 target 数远小于总输出数）
    - 避免回退 CPU argsort（2亿元素 CPU argsort 需 30-40s），残差从 64s 降到 ~10s

    [优化一] 用 argsort + reduceat 代替 np.unique + add.at：
    - np.unique(return_inverse=True) 对 1340 万元素需 2.5s
    - argsort + reduceat 只需 1.8s（int32）/ 2.1s（int64），加速 1.2-1.5x

    [优化二] GPU argsort（稳定 radix sort 携带 index）：
    - 1340 万元素：CPU argsort 1.0s → GPU 0.25s，残差整体 1.8s→0.59s，加速 3x
    - 仅支持 int32（max<2^31），int64 回退 CPU
    - 需传入 gpu_argsort 对象（GPUArgsort 类）"""
    n = len(unique_idx)
    GPU_SAFE_LIMIT = 50_000_000  # GPU radix sort stable up to ~60M

    def _merge(targets, values):
        """Argsort + reduceat merge. Returns (unique_targets, merged_values)."""
        N = len(targets)
        if N == 0:
            return targets, values
        if targets.max() < (1 << 31):
            t_sort = targets.astype(np.int32)
            use_i32 = True
        else:
            t_sort = targets
            use_i32 = False

        use_gpu = (gpu_argsort is not None and N > 10000
                   and N <= gpu_argsort.max_n and N <= GPU_SAFE_LIMIT)
        if use_gpu:
            from geoqc.gpu import GPUArgsort, GPUArgsort64
            if use_i32 and isinstance(gpu_argsort, GPUArgsort):
                t_s, s_idx = gpu_argsort.argsort(t_sort)
                v_s = values[s_idx]
            elif (not use_i32) and isinstance(gpu_argsort, GPUArgsort64):
                t_s, s_idx = gpu_argsort.argsort(t_sort)
                if s_idx.max() >= N or s_idx.min() < 0:
                    order = np.argsort(t_sort)
                    t_s = t_sort[order]
                    v_s = values[order]
                else:
                    v_s = values[s_idx]
            else:
                order = np.argsort(t_sort)
                t_s = t_sort[order]
                v_s = values[order]
        else:
            order = np.argsort(t_sort)
            t_s = t_sort[order]
            v_s = values[order]

        diff = np.empty(N, dtype=bool)
        diff[0] = True
        diff[1:] = t_s[1:] != t_s[:-1]
        u = t_s[diff]
        bounds = np.nonzero(diff)[0]
        w = np.add.reduceat(v_s, bounds)
        return u.astype(np.int64), w

    # Chunked collection: collect states until chunk full, then merge immediately
    # This avoids huge memory allocation (proven 5.6x faster than single concatenate)
    chunk_t = []
    chunk_v = []
    chunk_size = 0
    all_u = []
    all_w = []

    for j in range(n):
        c = coeffs[j]
        if c == 0.0:
            continue
        t_idx, t_val = H_cols[int(unique_idx[j])]
        chunk_t.append(t_idx)
        chunk_v.append(c * t_val)
        chunk_size += len(t_idx)

        if chunk_size >= residual_chunk:
            ct = np.concatenate(chunk_t)
            cv = np.concatenate(chunk_v)
            u, w = _merge(ct, cv)
            all_u.append(u)
            all_w.append(w)
            chunk_t = []
            chunk_v = []
            chunk_size = 0

    if chunk_t:
        ct = np.concatenate(chunk_t)
        cv = np.concatenate(chunk_v)
        u, w = _merge(ct, cv)
        all_u.append(u)
        all_w.append(w)

    # Final cross-chunk merge
    if all_u:
        u, w = _merge(np.concatenate(all_u), np.concatenate(all_w))
    else:
        return 0.0, np.array([], dtype=np.int64), np.array([], dtype=np.float64)

    # Separate in-space and out-of-space
    pos = np.searchsorted(unique_idx, u)
    in_space = pos < n
    if in_space.any():
        in_space[in_space] &= unique_idx[pos[in_space]] == u[in_space]

    r_in_norm_sq = 0.0
    if in_space.any():
        r_vals = w[in_space] - E * coeffs[pos[in_space]]
        r_in_norm_sq = float(np.sum(r_vals ** 2))

    out_mask = ~in_space
    r_out_idx = u[out_mask]
    r_out_vals = w[out_mask]

    return np.sqrt(r_in_norm_sq), r_out_idx, r_out_vals


def compute_pt2_correction(r_out_idx, r_out_vals, E0, apply_fn, hd_fn, db,
                            az_of, bz_of, rt_a, rt_b,
                            top_n=50000, chunk_size=200):
    """PT2 energy correction (Epstein-Nesbet, diagonal approximation).

    E_PT2 = sum_{D not in V} |r_D|^2 / (E0 - H_DD)

    Geometric interpretation: this is the diagonal approximation of the
    normal-Hessian correction E_corr = -<r| (P_out H P_out - E0 I)^{-1} |r>,
    where r = P_out H|psi> is the normal residual vector on the Grassmannian.
    The full inverse is infeasible at dim=10^15; the diagonal approximation
    (Epstein-Nesbet PT2) is the standard first step.

    Only the top-N residual determinants are evaluated (PT2 is dominated by
    large residuals; tail contribution is negligible).

    Key optimisation: diagonal elements are identified by DIRECT BITSTRING
    COMPARISON (t_az == source_az AND t_bz == source_bz), avoiding the
    extremely expensive RankTable.rank() call (which does np.argsort on a
    (n, n_orb) matrix — 2GB temporary memory per chunk at n=2.5M).

    Parameters
    ----------
    r_out_idx : (M,) int array — out-of-space determinant combined indices
    r_out_vals : (M,) float array — residual values r_D = <D|H|psi>
    E0 : float — current variational energy
    apply_fn : callable — sparse action (includes two-body diagonal)
    hd_fn : callable — one-body diagonal + nuc lookup
    db, az_of, bz_of : rank lookup tables (rt_a/rt_b NOT needed)
    top_n : int — number of top residual determinants (default 50k)
    chunk_size : int — apply_fn batch size (default 200, ~10M outputs/batch)

    Returns
    -------
    E_pt2 : float — PT2 energy correction (should be negative)
    n_evaluated : int — number of determinants actually evaluated
    """
    import gc as _gc

    n_out = len(r_out_idx)
    if n_out == 0:
        return 0.0, 0

    # Select top-N by |r_D| using argpartition (O(n), not full sort O(n log n))
    if n_out > top_n:
        top_idx = np.argpartition(-np.abs(r_out_vals), top_n)[:top_n]
        eval_idx = r_out_idx[top_idx]
        eval_r = r_out_vals[top_idx]
    else:
        eval_idx = r_out_idx
        eval_r = r_out_vals

    n_eval = len(eval_idx)
    pt2_sum = 0.0

    # Chunked apply_fn to compute H_DD (avoid output buffer overflow)
    for c0 in range(0, n_eval, chunk_size):
        c1 = min(c0 + chunk_size, n_eval)
        chunk_idx = eval_idx[c0:c1]
        chunk_r = eval_r[c0:c1]
        n_chunk = len(chunk_idx)

        # Source bitstrings
        src_az = az_of[chunk_idx // db]
        src_bz = bz_of[chunk_idx % db]
        vals = np.ones(n_chunk, dtype=complex)
        result = apply_fn(src_az, src_bz, vals)
        if len(result) == 4:
            t_az, t_bz, t_v, src_idx = result
        else:
            t_az, t_bz, t_v = result
            per_src = len(t_az) // n_chunk
            src_idx = np.repeat(np.arange(n_chunk, dtype=np.int32), per_src)

        t_v_real = np.asarray(t_v).real

        # Diagonal elements: target bitstring == source bitstring.
        # DIRECT comparison — no RankTable.rank needed (avoids argsort
        # on (n, n_orb) matrix which was the memory/time bottleneck).
        diag_mask = ((t_az == src_az[src_idx]) &
                     (t_bz == src_bz[src_idx]))
        if diag_mask.any():
            diag_src = src_idx[diag_mask]   # local source of each diag term
            diag_v = t_v_real[diag_mask]    # two-body diag term value

            # A single source may have MULTIPLE diagonal terms (different
            # double-excitation paths ijab that return to D).  Accumulate
            # them per local source index with bincount.
            two_body_sum = np.bincount(diag_src, weights=diag_v,
                                        minlength=n_chunk)
            has_diag = two_body_sum != 0.0
            src_with_diag = np.where(has_diag)[0]

            # One-body diagonal + nuc added ONCE per source (not per term)
            one_body_diag = np.asarray(
                hd_fn(chunk_idx[src_with_diag])).real
            h_dd = two_body_sum[src_with_diag] + one_body_diag

            # PT2: |r_D|^2 / (E0 - H_DD)
            r_sq = chunk_r[src_with_diag] ** 2
            denom = E0 - h_dd
            denom = np.where(np.abs(denom) < 1e-8, 1e-8, denom)
            pt2_sum += float(np.sum(r_sq / denom))

        # Free chunk memory
        del t_az, t_bz, t_v, t_v_real, src_idx, result
        del src_az, src_bz, vals, chunk_idx, chunk_r
        if diag_mask.any():
            del diag_mask, diag_src, diag_v, two_body_sum, has_diag
            del src_with_diag, one_body_diag, h_dd
        _gc.collect()

    return pt2_sum, n_eval


